// Glyph stand-ins: a scene may draw one character as another, in its own colour.
Scenes.plainCell = Scenes.cell;
Scenes.cell = function (scene, ch, x, y, f) {
    if (scene.glyphs && ch in scene.glyphs) {
        let g = scene.glyphs[ch];
        if (Array.isArray(g)) {
            return g; // [character, colour]
        }
        return [g, this.plainCell(scene, ch, x, y, f)[1]]; // coloured like the stand-in
    }
    return this.plainCell(scene, ch, x, y, f);
};
